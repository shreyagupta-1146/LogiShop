CREATE TABLE logistics.geofence (
    geofence_id   TEXT PRIMARY KEY,
    name          TEXT NOT NULL,
    geofence_type TEXT NOT NULL CHECK (geofence_type IN ('WAREHOUSE', 'DELIVERY_ZONE')),
    boundary      POLYGON NOT NULL,                                    -- (lon, lat) corner points
    bbox          BOX    GENERATED ALWAYS AS (box(boundary)) STORED,
    center_lon    DOUBLE PRECISION GENERATED ALWAYS AS ((center(box(boundary)))[0]) STORED,
    center_lat    DOUBLE PRECISION GENERATED ALWAYS AS ((center(box(boundary)))[1]) STORED
);
CREATE INDEX idx_geofence_boundary ON logistics.geofence USING gist (boundary);   -- point-in-polygon queries

CREATE TABLE logistics.warehouse (
    warehouse_id TEXT PRIMARY KEY,
    name         TEXT NOT NULL,
    address      TEXT NOT NULL,
    geofence_id  TEXT NOT NULL UNIQUE REFERENCES logistics.geofence (geofence_id),     -- 1:1
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE logistics.vehicle (
    vehicle_id      TEXT PRIMARY KEY,
    registration_no TEXT NOT NULL UNIQUE,
    vehicle_type    TEXT NOT NULL CHECK (vehicle_type IN ('BIKE', 'VAN', 'TRUCK'))
);

CREATE TABLE logistics.staff_user (
    staff_id      TEXT PRIMARY KEY DEFAULT ('STF-' || nextval('logistics.staff_seq')),
    name          TEXT NOT NULL,
    email         CITEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    role          TEXT NOT NULL CHECK (role IN ('ADMIN', 'DRIVER')),
    vehicle_id    TEXT REFERENCES logistics.vehicle (vehicle_id),
    is_active     BOOLEAN NOT NULL DEFAULT true,
    CHECK ((role = 'DRIVER') = (vehicle_id IS NOT NULL))               -- every driver drives one vehicle
);

-- SHIPMENT: derived state, rebuilt by replaying shipment_event
CREATE TABLE logistics.shipment (
    shipment_id         TEXT PRIMARY KEY DEFAULT ('SHP-' || nextval('logistics.shipment_seq')),
    order_id            TEXT UNIQUE REFERENCES shop.customer_order (order_id) DEFERRABLE INITIALLY IMMEDIATE,   -- 1 order : 1 shipment
    customer_id         TEXT NOT NULL REFERENCES shop.customer (customer_id),
    origin_warehouse_id TEXT NOT NULL REFERENCES logistics.warehouse (warehouse_id),
    vehicle_id          TEXT REFERENCES logistics.vehicle (vehicle_id),
    zone_id             TEXT REFERENCES logistics.geofence (geofence_id),
    status              logistics.shipment_status NOT NULL DEFAULT 'CREATED',
    current_lat         DOUBLE PRECISION,
    current_lon         DOUBLE PRECISION,
    eta_original        TIMESTAMPTZ,
    eta_current         TIMESTAMPTZ,
    at_risk             BOOLEAN NOT NULL DEFAULT false,
    delivery_start      TIMESTAMPTZ NOT NULL,
    delivery_end        TIMESTAMPTZ NOT NULL,
    destination_address TEXT NOT NULL,
    dest_lat            DOUBLE PRECISION NOT NULL,
    dest_lon            DOUBLE PRECISION NOT NULL,
    stops_remaining     INTEGER NOT NULL DEFAULT 0 CHECK (stops_remaining >= 0),
    actual_delivery_at  TIMESTAMPTZ,
    created_at          TIMESTAMPTZ NOT NULL,
    updated_at          TIMESTAMPTZ NOT NULL,
    CHECK (delivery_end > delivery_start),
    CHECK ((current_lat IS NULL) = (current_lon IS NULL)),
    CHECK (current_lat IS NULL OR (current_lat BETWEEN -90 AND 90 AND current_lon BETWEEN -180 AND 180)),
    CHECK (dest_lat BETWEEN -90 AND 90 AND dest_lon BETWEEN -180 AND 180),
    CHECK ((status = 'DELIVERED') = (actual_delivery_at IS NOT NULL)),          -- delivered <=> delivery time recorded
    CHECK (status IN ('CREATED', 'EXCEPTION') OR vehicle_id IS NOT NULL)        -- no pick-up without a vehicle
);
CREATE INDEX idx_shipment_customer ON logistics.shipment (customer_id);
CREATE INDEX idx_shipment_status   ON logistics.shipment (status);
CREATE INDEX idx_shipment_vehicle  ON logistics.shipment (vehicle_id) WHERE vehicle_id IS NOT NULL;
CREATE INDEX idx_shipment_zone     ON logistics.shipment (zone_id);
CREATE INDEX idx_shipment_at_risk  ON logistics.shipment (shipment_id) WHERE at_risk;        -- partial index

CREATE TABLE logistics.shipment_item (
    shipment_id TEXT    NOT NULL REFERENCES logistics.shipment (shipment_id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
    sku_id      TEXT    NOT NULL REFERENCES shop.sku (sku_id),
    quantity    INTEGER NOT NULL CHECK (quantity >= 1),
    PRIMARY KEY (shipment_id, sku_id)
);
CREATE INDEX idx_shipment_item_sku ON logistics.shipment_item (sku_id);

-- SHIPMENT_EVENT: the append-only event log = source of truth (event sourcing)
CREATE TABLE logistics.shipment_event (
    log_seq     BIGINT GENERATED ALWAYS AS IDENTITY UNIQUE,            -- position in the log
    event_id    TEXT PRIMARY KEY,                                      -- idempotency key
    shipment_id TEXT NOT NULL REFERENCES logistics.shipment (shipment_id) DEFERRABLE INITIALLY IMMEDIATE,
    event_type  TEXT NOT NULL CHECK (event_type IN (
                    'SHIPMENT_CREATED', 'VEHICLE_ASSIGNED',
                    'PICKED_UP', 'IN_TRANSIT', 'OUT_FOR_DELIVERY', 'DELIVERED', 'EXCEPTION',
                    'ARRIVED_AT_ZONE', 'STOP_COMPLETED', 'DELIVERY_RESCHEDULED',
                    'REQUEST_SUBMITTED', 'REQUEST_ACCEPTED', 'REQUEST_REJECTED', 'REQUEST_UPDATED',
                    'ETA_UPDATE', 'EXCEPTION_RISK', 'RISK_CLEARED', 'EVENT_REJECTED')),
    event_time  TIMESTAMPTZ NOT NULL,
    payload     JSONB NOT NULL DEFAULT '{}'
);
CREATE INDEX idx_event_shipment ON logistics.shipment_event (shipment_id, log_seq);
CREATE INDEX idx_event_type     ON logistics.shipment_event (event_type);
CREATE INDEX idx_event_payload  ON logistics.shipment_event USING gin (payload jsonb_path_ops);   -- query inside the JSON

CREATE TABLE logistics.gps_ping (
    ping_id     BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    shipment_id TEXT NOT NULL REFERENCES logistics.shipment (shipment_id) DEFERRABLE INITIALLY IMMEDIATE,
    vehicle_id  TEXT NOT NULL REFERENCES logistics.vehicle (vehicle_id),
    ping_time   TIMESTAMPTZ NOT NULL,
    lat         DOUBLE PRECISION NOT NULL CHECK (lat BETWEEN -90 AND 90),
    lon         DOUBLE PRECISION NOT NULL CHECK (lon BETWEEN -180 AND 180),
    speed_kmh   REAL NOT NULL CHECK (speed_kmh >= 0 AND speed_kmh <= 200),
    heading_deg REAL NOT NULL CHECK (heading_deg >= 0 AND heading_deg <= 360)
);
CREATE INDEX idx_ping_shipment ON logistics.gps_ping (shipment_id, ping_time);
CREATE INDEX idx_ping_time     ON logistics.gps_ping USING brin (ping_time);      -- tiny index for time-ordered telemetry

CREATE TABLE logistics.inventory_ledger (
    ledger_id      BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    sku_id         TEXT    NOT NULL REFERENCES shop.sku (sku_id),
    warehouse_id   TEXT    NOT NULL REFERENCES logistics.warehouse (warehouse_id),
    movement_type  TEXT    NOT NULL CHECK (movement_type IN ('STOCK_IN', 'SHIPMENT_OUT', 'RETURN_IN')),
    quantity_delta INTEGER NOT NULL CHECK (quantity_delta <> 0),
    event_time     TIMESTAMPTZ NOT NULL,
    shipment_id    TEXT REFERENCES logistics.shipment (shipment_id) DEFERRABLE INITIALLY IMMEDIATE,
    request_id     TEXT,                                                -- FK added below (customer_request is created later)
    CHECK (
        (movement_type = 'STOCK_IN'     AND quantity_delta > 0 AND shipment_id IS NULL     AND request_id IS NULL) OR
        (movement_type = 'SHIPMENT_OUT' AND quantity_delta < 0 AND shipment_id IS NOT NULL AND request_id IS NULL) OR
        (movement_type = 'RETURN_IN'    AND quantity_delta > 0 AND shipment_id IS NULL     AND request_id IS NOT NULL)
    )
);
CREATE INDEX idx_ledger_sku_wh   ON logistics.inventory_ledger (warehouse_id, sku_id);
CREATE INDEX idx_ledger_shipment ON logistics.inventory_ledger (shipment_id);
CREATE UNIQUE INDEX uq_ledger_shipment_line ON logistics.inventory_ledger (shipment_id, sku_id) WHERE movement_type = 'SHIPMENT_OUT';
CREATE UNIQUE INDEX uq_ledger_return_line   ON logistics.inventory_ledger (request_id, sku_id)  WHERE movement_type = 'RETURN_IN';

CREATE TABLE logistics.inventory_balance (
    warehouse_id  TEXT    NOT NULL REFERENCES logistics.warehouse (warehouse_id),
    sku_id        TEXT    NOT NULL REFERENCES shop.sku (sku_id),
    available_qty INTEGER NOT NULL CHECK (available_qty >= 0),          -- never below zero
    updated_at    TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (warehouse_id, sku_id)
);

CREATE TABLE logistics.customer_request (
    request_id          TEXT PRIMARY KEY DEFAULT ('REQ-' || nextval('logistics.request_seq')),
    shipment_id         TEXT NOT NULL REFERENCES logistics.shipment (shipment_id) DEFERRABLE INITIALLY IMMEDIATE,
    customer_id         TEXT NOT NULL REFERENCES shop.customer (customer_id),
    request_type        TEXT NOT NULL CHECK (request_type IN ('RESCHEDULE', 'RETURN')),
    status              TEXT NOT NULL DEFAULT 'PENDING'
                        CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'PICKUP_SCHEDULED', 'PICKED_UP', 'COMPLETED')),
    reason              TEXT,
    requested_start     TIMESTAMPTZ,
    requested_end       TIMESTAMPTZ,
    pickup_scheduled_at TIMESTAMPTZ,
    created_at          TIMESTAMPTZ NOT NULL,
    updated_at          TIMESTAMPTZ NOT NULL,
    CHECK (request_type <> 'RESCHEDULE'
           OR (requested_start IS NOT NULL AND requested_end IS NOT NULL AND requested_end > requested_start)),
    CHECK (request_type <> 'RETURN' OR (requested_start IS NULL AND requested_end IS NULL)),
    CHECK (pickup_scheduled_at IS NULL OR request_type = 'RETURN'),
    CHECK ((request_type = 'RESCHEDULE' AND status IN ('PENDING', 'APPROVED', 'REJECTED')) OR
           (request_type = 'RETURN'     AND status IN ('PENDING', 'PICKUP_SCHEDULED', 'PICKED_UP', 'COMPLETED', 'REJECTED')))
);
CREATE INDEX idx_request_shipment ON logistics.customer_request (shipment_id);
CREATE INDEX idx_request_customer ON logistics.customer_request (customer_id);

ALTER TABLE logistics.inventory_ledger
    ADD CONSTRAINT fk_ledger_request FOREIGN KEY (request_id)
    REFERENCES logistics.customer_request (request_id) DEFERRABLE INITIALLY IMMEDIATE;

CREATE TABLE logistics.request_item (
    request_id     TEXT    NOT NULL REFERENCES logistics.customer_request (request_id) ON DELETE CASCADE,
    sku_id         TEXT    NOT NULL REFERENCES shop.sku (sku_id),
    quantity       INTEGER NOT NULL CHECK (quantity >= 1),
    item_condition TEXT    NOT NULL DEFAULT 'GOOD' CHECK (item_condition IN ('GOOD', 'OPENED', 'DAMAGED')),
    PRIMARY KEY (request_id, sku_id)
);

CREATE TABLE logistics.ml_prediction (
    prediction_id   BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    shipment_id     TEXT NOT NULL REFERENCES logistics.shipment (shipment_id) DEFERRABLE INITIALLY IMMEDIATE,
    prediction_type TEXT NOT NULL CHECK (prediction_type IN ('ETA', 'ANOMALY')),
    model_name      TEXT NOT NULL,
    model_version   TEXT NOT NULL,
    features        JSONB NOT NULL,
    predicted_eta   TIMESTAMPTZ,
    anomaly_score   REAL CHECK (anomaly_score IS NULL OR anomaly_score BETWEEN 0 AND 1),
    flagged         BOOLEAN NOT NULL DEFAULT false,
    created_at      TIMESTAMPTZ NOT NULL,
    abs_error_min   NUMERIC(8,2) CHECK (abs_error_min IS NULL OR abs_error_min >= 0),   -- filled after delivery
    CHECK ((prediction_type = 'ETA'     AND predicted_eta  IS NOT NULL) OR
           (prediction_type = 'ANOMALY' AND anomaly_score IS NOT NULL))
);
CREATE INDEX idx_pred_shipment ON logistics.ml_prediction (shipment_id, prediction_type);
CREATE INDEX idx_pred_model    ON logistics.ml_prediction (model_name);

CREATE TABLE logistics.notification (
    notification_id   BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    shipment_id       TEXT REFERENCES logistics.shipment (shipment_id) DEFERRABLE INITIALLY IMMEDIATE,
    order_id          TEXT REFERENCES shop.customer_order (order_id),
    customer_id       TEXT NOT NULL REFERENCES shop.customer (customer_id),
    notification_type TEXT NOT NULL CHECK (notification_type IN ('STATUS', 'ETA', 'REQUEST', 'ALERT')),
    message           TEXT NOT NULL,
    status            TEXT NOT NULL DEFAULT 'SENT' CHECK (status IN ('SENT', 'READ')),
    created_at        TIMESTAMPTZ NOT NULL,
    CHECK (shipment_id IS NOT NULL OR order_id IS NOT NULL)
);
CREATE INDEX idx_notif_customer ON logistics.notification (customer_id, created_at DESC);
CREATE INDEX idx_notif_shipment ON logistics.notification (shipment_id);

-- =====================================================================
--  SCHEMA infra
-- =====================================================================
-- idempotent consumers: every applied event id is recorded in the same transaction as its effects
CREATE TABLE infra.processed_event (
    consumer     TEXT NOT NULL,
    event_id     TEXT NOT NULL,
    processed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (consumer, event_id)
);

-- row-level change log written by the audit trigger on every business table
CREATE TABLE infra.audit_log (
    change_id  BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ts         TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    table_name TEXT NOT NULL,
    op         TEXT NOT NULL CHECK (op IN ('INSERT', 'UPDATE', 'DELETE')),
    pk         TEXT,
    old_row    JSONB,
    new_row    JSONB,
    actor      TEXT NOT NULL,           -- the application component (or the SQL user) that made the change
    trace_id   TEXT                     -- the user action that caused it
);
CREATE INDEX idx_audit_trace ON infra.audit_log (trace_id);
CREATE INDEX idx_audit_table ON infra.audit_log (table_name, change_id DESC);

-- transactional outbox: written in the SAME transaction as the order, published to Kafka afterwards
CREATE TABLE infra.outbox (
    outbox_id    BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    topic        TEXT NOT NULL,
    msg_key      TEXT NOT NULL,
    payload      JSONB NOT NULL,
    trace_id     TEXT,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    published_at TIMESTAMPTZ
);
CREATE INDEX idx_outbox_pending ON infra.outbox (outbox_id) WHERE published_at IS NULL;

CREATE TABLE infra.auth_session (
    token_hash   TEXT PRIMARY KEY,                       -- SHA-256 of the cookie value
    subject_type TEXT NOT NULL CHECK (subject_type IN ('CUSTOMER', 'STAFF')),
    subject_id   TEXT NOT NULL,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at   TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_session_expiry ON infra.auth_session (expires_at);

