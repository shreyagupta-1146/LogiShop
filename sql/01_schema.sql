-- =====================================================================
--  01  SCHEMA  -  tables, keys, constraints, indexes   (PostgreSQL 16)
--
--  schema shop       catalogue, customers, addresses, carts, orders, payments
--  schema logistics  the 15 relations of the design document (BCNF) + staff:
--                    warehouse, geofence, vehicle, shipment, shipment_item,
--                    shipment_event, gps_ping, inventory_ledger, inventory_balance,
--                    customer_request, request_item, ml_prediction, notification
--  schema infra      audit_log, outbox, processed_event, auth_session
--
--  Design decisions
--   * readable business keys (CUS-7, ORD-1001, SHP-101, SKU-1001) generated by SEQUENCES
--   * money is NUMERIC(12,2), never floating point; times are TIMESTAMPTZ (stored in UTC)
--   * statuses that drive the lifecycle are ENUM types
--   * geofence boundaries are native POLYGON values with a GiST index (the "2dsphere" of
--     the Mongo design); the bounding box and centre are GENERATED columns
--   * every foreign key that points at the rebuildable projections is DEFERRABLE, so a
--     rebuild-from-event-log can run inside one transaction
-- =====================================================================
SET ROLE logistics_owner;

-- ---------------------------------------------------------------------
--  sequences and types
-- ---------------------------------------------------------------------
CREATE SEQUENCE shop.customer_seq     START 1;
CREATE SEQUENCE shop.order_seq        START 1001;
CREATE SEQUENCE shop.payment_seq      START 5001;
CREATE SEQUENCE logistics.shipment_seq START 1;
CREATE SEQUENCE logistics.request_seq  START 5001;
CREATE SEQUENCE logistics.staff_seq    START 1;

CREATE TYPE logistics.shipment_status AS ENUM
    ('CREATED', 'PICKED_UP', 'IN_TRANSIT', 'OUT_FOR_DELIVERY', 'DELIVERED', 'EXCEPTION');
CREATE TYPE shop.order_status AS ENUM
    ('PLACED', 'CONFIRMED', 'SHIPPED', 'OUT_FOR_DELIVERY', 'DELIVERED', 'DELAYED', 'CANCELLED');

-- =====================================================================
--  SCHEMA shop
-- =====================================================================
CREATE TABLE shop.category (
    category_id SMALLINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    slug        TEXT NOT NULL UNIQUE,
    name        TEXT NOT NULL,
    parent_id   SMALLINT REFERENCES shop.category (category_id)        -- categories form a tree
);

-- SKU = the sellable product (relation SKU of the design document, extended with commerce columns)
CREATE TABLE shop.sku (
    sku_id           TEXT PRIMARY KEY,
    sku_code         TEXT NOT NULL UNIQUE,
    description      TEXT NOT NULL,                                     -- product title
    long_description TEXT,
    brand            TEXT NOT NULL,
    category_id      SMALLINT NOT NULL REFERENCES shop.category (category_id),
    weight_kg        NUMERIC(6,3) NOT NULL CHECK (weight_kg > 0),
    mrp              NUMERIC(10,2) NOT NULL CHECK (mrp > 0),            -- printed price
    price            NUMERIC(10,2) NOT NULL CHECK (price > 0),          -- selling price
    image_emoji      TEXT NOT NULL DEFAULT '📦',
    image_color      TEXT NOT NULL DEFAULT '#e8efff',
    is_active        BOOLEAN NOT NULL DEFAULT true,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    search_vec       TSVECTOR GENERATED ALWAYS AS (
                         to_tsvector('simple', description || ' ' || brand || ' ' || coalesce(long_description, ''))
                     ) STORED,
    CHECK (price <= mrp)
);
CREATE INDEX idx_sku_category ON shop.sku (category_id) WHERE is_active;
CREATE INDEX idx_sku_search   ON shop.sku USING gin (search_vec);               -- full-text search
CREATE INDEX idx_sku_trgm     ON shop.sku USING gin (description gin_trgm_ops); -- fuzzy "LIKE '%case%'"

CREATE TABLE shop.price_history (                                    -- filled by a trigger
    history_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    sku_id     TEXT NOT NULL REFERENCES shop.sku (sku_id),
    old_price  NUMERIC(10,2) NOT NULL,
    new_price  NUMERIC(10,2) NOT NULL,
    changed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    changed_by TEXT NOT NULL
);

CREATE TABLE shop.customer (
    customer_id   TEXT PRIMARY KEY DEFAULT ('CUS-' || nextval('shop.customer_seq')),
    name          TEXT NOT NULL CHECK (length(btrim(name)) > 0),
    email         CITEXT NOT NULL UNIQUE
                  CHECK (email ~ '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$'),
    phone         TEXT CHECK (phone ~ '^\+?[0-9][0-9 -]{6,14}$'),
    password_hash TEXT NOT NULL,                                       -- PBKDF2-SHA256, never plain text
    is_active     BOOLEAN NOT NULL DEFAULT true,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE shop.customer_address (
    address_id  BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    customer_id TEXT NOT NULL REFERENCES shop.customer (customer_id) ON DELETE CASCADE,
    label       TEXT NOT NULL DEFAULT 'Home' CHECK (label IN ('Home', 'Work', 'Other')),
    recipient   TEXT NOT NULL,
    phone       TEXT NOT NULL,
    line1       TEXT NOT NULL,
    line2       TEXT,
    locality    TEXT NOT NULL,
    city        TEXT NOT NULL DEFAULT 'Bengaluru',
    state       TEXT NOT NULL DEFAULT 'Karnataka',
    pincode     TEXT NOT NULL CHECK (pincode ~ '^[0-9]{6}$'),
    lat         DOUBLE PRECISION NOT NULL CHECK (lat BETWEEN -90 AND 90),
    lon         DOUBLE PRECISION NOT NULL CHECK (lon BETWEEN -180 AND 180),
    is_default  BOOLEAN NOT NULL DEFAULT false,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX        idx_address_customer ON shop.customer_address (customer_id);
CREATE UNIQUE INDEX uq_default_address   ON shop.customer_address (customer_id) WHERE is_default;   -- at most one default

CREATE TABLE shop.cart_item (                                        -- one active cart per customer
    customer_id TEXT NOT NULL REFERENCES shop.customer (customer_id) ON DELETE CASCADE,
    sku_id      TEXT NOT NULL REFERENCES shop.sku (sku_id),
    quantity    INTEGER NOT NULL CHECK (quantity BETWEEN 1 AND 10),
    added_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (customer_id, sku_id)
);

CREATE TABLE shop.customer_order (
    order_id       TEXT PRIMARY KEY DEFAULT ('ORD-' || nextval('shop.order_seq')),
    customer_id    TEXT NOT NULL REFERENCES shop.customer (customer_id),
    address_id     BIGINT REFERENCES shop.customer_address (address_id) ON DELETE SET NULL,
    -- the delivery address is copied (snapshot): editing the address book must not alter past orders
    ship_recipient TEXT NOT NULL,
    ship_phone     TEXT NOT NULL,
    ship_address   TEXT NOT NULL,
    ship_lat       DOUBLE PRECISION NOT NULL,
    ship_lon       DOUBLE PRECISION NOT NULL,
    placed_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    status         shop.order_status NOT NULL DEFAULT 'PLACED',
    subtotal       NUMERIC(12,2) NOT NULL CHECK (subtotal >= 0),
    delivery_fee   NUMERIC(8,2)  NOT NULL DEFAULT 0 CHECK (delivery_fee >= 0),
    total          NUMERIC(12,2) NOT NULL,
    payment_method TEXT NOT NULL CHECK (payment_method IN ('UPI', 'CARD', 'NETBANKING', 'COD')),
    cancel_reason  TEXT,
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (total = subtotal + delivery_fee),
    CHECK ((status = 'CANCELLED') = (cancel_reason IS NOT NULL))
);
CREATE INDEX idx_order_customer ON shop.customer_order (customer_id, placed_at DESC);
CREATE INDEX idx_order_status   ON shop.customer_order (status);

CREATE TABLE shop.order_line (
    order_id   TEXT NOT NULL REFERENCES shop.customer_order (order_id),
    sku_id     TEXT NOT NULL REFERENCES shop.sku (sku_id),
    quantity   INTEGER NOT NULL CHECK (quantity >= 1),
    unit_price NUMERIC(10,2) NOT NULL CHECK (unit_price > 0),         -- price at the time of purchase
    line_total NUMERIC(12,2) GENERATED ALWAYS AS (quantity * unit_price) STORED,
    PRIMARY KEY (order_id, sku_id)
);
CREATE INDEX idx_order_line_sku ON shop.order_line (sku_id);

CREATE TABLE shop.payment (
    payment_id TEXT PRIMARY KEY DEFAULT ('PAY-' || nextval('shop.payment_seq')),
    order_id   TEXT NOT NULL REFERENCES shop.customer_order (order_id),
    kind       TEXT NOT NULL CHECK (kind IN ('CHARGE', 'REFUND')),
    method     TEXT NOT NULL CHECK (method IN ('UPI', 'CARD', 'NETBANKING', 'COD')),
    amount     NUMERIC(12,2) NOT NULL CHECK (amount > 0),
    status     TEXT NOT NULL CHECK (status IN ('PENDING', 'PAID', 'REFUNDED', 'FAILED')),
    reference  TEXT,                                                   -- simulated gateway reference, no card data is stored
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uq_one_charge_per_order ON shop.payment (order_id) WHERE kind = 'CHARGE';
CREATE INDEX        idx_payment_order       ON shop.payment (order_id);

-- =====================================================================
